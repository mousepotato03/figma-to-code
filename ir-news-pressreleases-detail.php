            <h1 class="article-title">나이벡, siRNA 치료제 뇌 전달 전임상 성과 공개 ... 행동지표 개선까지 확인</h1>
            <time class="article-date" datetime="2025-12-10">2025-12-10</time>
          </header>

          <div class="article-body">
            <figure class="article-image">
              <img src="assets/images/ir-news-pressreleases-detail/photo.png" alt="보도자료 이미지">
            </figure>

            <div class="article-text">
              <p>나이벡(대표 정종평)은 10일 혈관뇌장벽을 넘어 siRNA 치료제를 뇌 내부에 장기간 전달하고, 행동지표 개선으로 이어졌다는 전임상 결과를 발표했다고 밝혔다.</p>

              <p>이 결과는 지난 9일부터 사흘간 미국 보스턴에서 열리는 CNS Drug Delivery Summit에서 포스터 형태로 발표됐다. 이 행사는 중추신경계 약물전달 기술과 신경과학 연구를 다루는 글로벌 학술대회다.</p>

              <p>나이벡 관계자는 "이번 연구는 자체 개발한 NIPEP-TPP 기반의 뇌 표적 약물전달 플랫폼 'PEPTARDEL-TB3'을 활용해 중추신경계 치료제의 실제 작동 가능성을 검증하는 데 초점을 맞췄다"며 "단순히 약물이 뇌에 도달하는지를 확인하는 수준을 넘어, 전뇌 분포, 뇌 내 지속성, 표적 유전자 조절, 행동 개선까지 연속적으로 평가한 점에서 의미가 크다"고 설명했다.</p>

              <p>연구팀은 알츠하이머병 관련 유전자인 BACE1을 표적하는 siRNA를 PEPTARDEL-TB3 플랫폼과 복합체 형태로 제조해 생쥐에 정맥투여했다. 그 결과 대뇌피질(cortex), 소뇌(cerebellum), 중뇌(midbrain) 등 주요 뇌 부위 전반에서 BACE1 siRNA가 광범위하게 분포했으며, 투여 후 최대 7일간 뇌 내에서 신호가 유지된 것으로 나타났다.</p>

              <p>더불어 이들은 표적 유전자 억제 효과도 확인됐다. PEPTARDEL-TB3와 BACE1 siRNA 복합체 투여군에서 BACE1 유전자와 단백질 발현이 유의하게 감소했고, 이러한 분자적 변화는 행동지표 개선으로 이어졌다.</p>

              <p>회사 측에 따르면, 둥지 만들기 평가, 새로운 물체 인지 평가, 수중 미로 테스트에서 인지 및 학습 능력 회복을 시사하는 결과가 관찰돼 플랫폼이 실제 기능적 효과로 연결될 수 있는 것으로 확인됐다.</p>

              <p>회사 관계자는 "PEPTARDEL-TB3가 펩타이드 기반 플랫폼으로서 다양한 치료제와 결합할 수 있고, siRNA와 ASO 등 차세대 RNA 기반 치료제 전달에도 폭넓게 적용할 수 있다는 점에서 확장성이 크다"며 "회사는 이번 전임상을 기반으로 알츠하이머병, 파킨슨병, 루게릭병, 희귀 유전성 뇌질환 등 다양한 중추신경계 적응증으로 개발 범위를 확대할 계획"이고 말했다.</p>

              <p>정종평 대표는 "이번 연구는 플랫폼의 실질적인 치료 가능성을 검증하기 위해 설계된 실험이었다. 뇌 깊은 영역까지 치료제를 전달하고 장기간 유지되고, 유전자 조절과 행동 개선까지 확인한 것은 기술적 진전"이라며 "다양한 신경계 적응증으로의 확장과 글로벌 파트너십 논의를 본격화할 것"이라고 밝혔다.</p>

